-- Colunas em subscriptions
ALTER TABLE public.subscriptions
  ADD COLUMN IF NOT EXISTS trial_start_date date,
  ADD COLUMN IF NOT EXISTS trial_end_date date,
  ADD COLUMN IF NOT EXISTS account_blocked boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.subscriptions.account_blocked IS
  'true = conta bloqueada (trial expirado, pagamento falhou, cancelamento Stripe, etc.).';

-- 2) CPF normalizado apenas dígitos no perfil
ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS cpf text NOT NULL DEFAULT '';

-- 3) Identificadores de trial (somente hashes; SEM dados em claro).
CREATE TABLE IF NOT EXISTS public.trial_identifier_claims (
  id uuid PRIMARY KEY DEFAULT uuid_generate_v4 (),
  kind text NOT NULL CHECK (
    kind = ANY (
      ARRAY['email','cpf','phone','device','ip_subnet'::text]
    )
  ),
  value_hash text NOT NULL,
  user_id uuid NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now (),
  UNIQUE (kind, value_hash)
);

CREATE INDEX IF NOT EXISTS idx_trial_claims_user_id ON public.trial_identifier_claims (user_id);

-- 4) Rate limit bruteforce cadastro por IP (gravado via service_role)
CREATE TABLE IF NOT EXISTS public.signup_rate_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip inet NOT NULL,
  occurred_at timestamptz NOT NULL DEFAULT now ()
);

CREATE INDEX IF NOT EXISTS idx_signup_rate_ip_time ON public.signup_rate_events (ip, occurred_at DESC);

ALTER TABLE public.trial_identifier_claims ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.signup_rate_events ENABLE ROW LEVEL SECURITY;

