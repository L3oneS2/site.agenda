-- Perfis (1:1 com auth.users)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
  nome TEXT NOT NULL DEFAULT '',
  telefone TEXT NOT NULL DEFAULT '',
  role public.profile_role NOT NULL DEFAULT 'client',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Barbearias (um barbeiro = uma barbearia neste MVP)
CREATE TABLE IF NOT EXISTS public.barbershops (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id UUID NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  nome_barbearia TEXT NOT NULL,
  endereco TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id)
);

CREATE INDEX IF NOT EXISTS idx_barbershops_user_id ON public.barbershops (user_id);

-- Assinaturas Stripe
CREATE TABLE IF NOT EXISTS public.subscriptions (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id UUID NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  status public.subscription_status NOT NULL DEFAULT 'expired',
  stripe_customer_id TEXT,
  stripe_subscription_id TEXT UNIQUE,
  current_period_end TIMESTAMPTZ,
  trial_start_date DATE,
  trial_end_date DATE,
  account_blocked BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id)
);

CREATE INDEX IF NOT EXISTS idx_subscriptions_user_id ON public.subscriptions (user_id);
CREATE INDEX IF NOT EXISTS idx_subscriptions_status ON public.subscriptions (status);

-- Anti-fraude trial (hashes) e rate limit de cadastro (gravado via service_role / funções)
CREATE TABLE IF NOT EXISTS public.trial_identifier_claims (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4 (),
  kind TEXT NOT NULL CHECK (
    kind = ANY (
      ARRAY['email','phone','device','ip_subnet'::text]
    )
  ),
  value_hash TEXT NOT NULL,
  user_id UUID NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now (),
  UNIQUE (kind, value_hash)
);

CREATE INDEX IF NOT EXISTS idx_trial_claims_user_id ON public.trial_identifier_claims (user_id);

CREATE TABLE IF NOT EXISTS public.signup_rate_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip INET NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now ()
);

CREATE INDEX IF NOT EXISTS idx_signup_rate_ip_time ON public.signup_rate_events (ip, occurred_at DESC);

ALTER TABLE public.trial_identifier_claims ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.signup_rate_events ENABLE ROW LEVEL SECURITY;

-- Ofertas de horário por data (inícios explícitos cadastrados pelo barbeiro)
CREATE TABLE IF NOT EXISTS public.agenda_day_slots (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id UUID NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  data DATE NOT NULL,
  hora TIME NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id, data, hora)
);

CREATE INDEX IF NOT EXISTS idx_agenda_day_slots_user_data ON public.agenda_day_slots (user_id, data);

-- Serviços oferecidos pelo barbeiro
CREATE TABLE IF NOT EXISTS public.services (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id UUID NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  nome TEXT NOT NULL,
  preco NUMERIC(10, 2) NOT NULL DEFAULT 0,
  duracao_minutos SMALLINT NOT NULL CHECK (duracao_minutos > 0 AND duracao_minutos <= 720),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_services_user_id ON public.services (user_id);

-- Agendamentos (intervalo de tempo + serviço opcional para registros legados)
CREATE TABLE IF NOT EXISTS public.appointments (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  barber_id UUID NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  servico_id UUID REFERENCES public.services (id) ON DELETE SET NULL,
  cliente_nome TEXT NOT NULL,
  cliente_telefone TEXT NOT NULL,
  cliente_email TEXT,
  data DATE NOT NULL,
  hora_inicio TIME NOT NULL,
  hora_fim TIME NOT NULL,
  status public.appointment_status NOT NULL DEFAULT 'scheduled',
  access_token UUID NOT NULL DEFAULT gen_random_uuid(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT appointment_time_order CHECK (hora_fim > hora_inicio),
  CONSTRAINT appointments_access_token_unique UNIQUE (access_token)
);

CREATE INDEX IF NOT EXISTS idx_appointments_barber_date ON public.appointments (barber_id, data);
CREATE INDEX IF NOT EXISTS idx_appointments_barber_date_start
